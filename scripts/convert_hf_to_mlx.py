#!/usr/bin/env python3
"""Convert the pinned KInIT Slovak Whisper checkpoint to MLX.

Unlike the upstream mlx-examples converter released with mlx-whisper 0.4.3,
this loader understands Hugging Face sharded safetensors checkpoints through
their model.safetensors.index.json weight map.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import math
import platform
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import Iterator

SOURCE_MODEL = "kinit/whisper-large-v3-sk"
SOURCE_REVISION = "8654a11704f3564ac53a4b266a567bd4f20c8c51"


def remap_hf_key(key: str) -> str | None:
    """Map a Transformers Whisper state-dict key to mlx-whisper 0.4.3."""
    if key == "proj_out.weight":
        # Whisper ties the output projection to decoder.token_embedding.
        return None

    key = key.replace("model.", "", 1)
    key = key.replace(".layers", ".blocks")
    key = key.replace(".self_attn", ".attn")
    key = key.replace(".attn_layer_norm", ".attn_ln")
    key = key.replace(".encoder_attn.", ".cross_attn.")
    key = key.replace(".encoder_attn_layer_norm", ".cross_attn_ln")
    key = key.replace(".final_layer_norm", ".mlp_ln")
    key = key.replace(".q_proj", ".query")
    key = key.replace(".k_proj", ".key")
    key = key.replace(".v_proj", ".value")
    key = key.replace(".out_proj", ".out")
    key = key.replace(".fc1", ".mlp1")
    key = key.replace(".fc2", ".mlp2")
    key = key.replace("embed_positions.weight", "positional_embedding")
    key = key.replace("decoder.embed_tokens", "decoder.token_embedding")
    key = key.replace("encoder.layer_norm", "encoder.ln_post")
    key = key.replace("decoder.layer_norm", "decoder.ln")

    # The encoder sinusoid is generated by mlx-whisper and is not a parameter.
    if key == "encoder.positional_embedding":
        return None
    return key


def mlx_dimensions(hf_config: dict) -> dict:
    """Extract the architecture fields consumed by mlx-whisper."""
    return {
        "n_mels": hf_config["num_mel_bins"],
        "n_audio_ctx": hf_config["max_source_positions"],
        "n_audio_state": hf_config["d_model"],
        "n_audio_head": hf_config["encoder_attention_heads"],
        "n_audio_layer": hf_config["encoder_layers"],
        "n_vocab": hf_config["vocab_size"],
        "n_text_ctx": hf_config["max_target_positions"],
        "n_text_state": hf_config["d_model"],
        "n_text_head": hf_config["decoder_attention_heads"],
        "n_text_layer": hf_config["decoder_layers"],
    }


def resolve_source(source: str, revision: str) -> Path:
    candidate = Path(source).expanduser()
    if candidate.is_dir():
        return candidate.resolve()

    from huggingface_hub import snapshot_download

    return Path(
        snapshot_download(
            repo_id=source,
            revision=revision,
            allow_patterns=[
                "*.json",
                "*.txt",
                "*.model",
                "model*.safetensors",
            ],
        )
    )


def weight_files(source_dir: Path) -> list[Path]:
    index_path = source_dir / "model.safetensors.index.json"
    if index_path.is_file():
        index = json.loads(index_path.read_text())
        names = list(dict.fromkeys(index["weight_map"].values()))
        files = [source_dir / name for name in names]
    elif (source_dir / "model.safetensors").is_file():
        files = [source_dir / "model.safetensors"]
    else:
        files = sorted(source_dir.glob("model-*.safetensors"))

    if not files or any(not path.is_file() for path in files):
        missing = [str(path) for path in files if not path.is_file()]
        raise FileNotFoundError(f"Incomplete safetensors checkpoint; missing={missing}")
    return files


def iter_hf_tensors(files: list[Path]) -> Iterator[tuple[str, object]]:
    from safetensors import safe_open

    seen: set[str] = set()
    for path in files:
        with safe_open(path, framework="pt", device="cpu") as handle:
            for key in handle.keys():
                if key in seen:
                    raise ValueError(f"Duplicate tensor {key!r} across checkpoint shards")
                seen.add(key)
                yield key, handle.get_tensor(key)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(8 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def convert(source: str, revision: str, output: Path, dtype_name: str) -> dict:
    import mlx.core as mx
    import numpy as np
    from mlx.utils import tree_flatten
    from mlx_whisper.whisper import ModelDimensions, Whisper

    if dtype_name not in {"float16", "float32"}:
        raise ValueError("dtype must be float16 or float32")
    dtype = getattr(mx, dtype_name)

    source_dir = resolve_source(source, revision)
    hf_config = json.loads((source_dir / "config.json").read_text())
    generation_config_path = source_dir / "generation_config.json"
    if not generation_config_path.is_file():
        raise FileNotFoundError("generation_config.json is required to preserve alignment heads")
    generation_config = json.loads(generation_config_path.read_text())
    alignment_heads = generation_config.get("alignment_heads")
    if not alignment_heads:
        raise ValueError("Source generation_config.json has no alignment_heads")
    dimensions = mlx_dimensions(hf_config)
    files = weight_files(source_dir)

    weights: dict[str, mx.array] = {}
    for hf_key, tensor in iter_hf_tensors(files):
        mlx_key = remap_hf_key(hf_key)
        if mlx_key is None:
            continue
        if mlx_key in weights:
            raise ValueError(f"Multiple source tensors mapped to {mlx_key!r}")

        # bfloat16 tensors cannot be passed through NumPy without an upcast.
        if str(tensor.dtype) == "torch.bfloat16":
            tensor = tensor.float()
        tensor = tensor.detach().cpu().contiguous()
        value = mx.array(tensor.numpy())
        if "conv" in mlx_key and value.ndim == 3:
            value = value.swapaxes(1, 2)
        weights[mlx_key] = value.astype(dtype)

    # Preserve KInIT's ten selected alignment heads. A stock local-HF
    # conversion silently falls back to all 320 heads in the decoder's last
    # half, which changes word-timestamp behavior.
    model = Whisper(ModelDimensions(**dimensions), dtype)
    model.set_alignment_heads(np.asarray(alignment_heads, dtype=np.int64))
    weights["alignment_heads"] = model.alignment_heads

    # Strict construction proves every converted key and shape matches MLX.
    model.load_weights(list(weights.items()), strict=True)
    mx.eval(model.parameters())
    # Use model-tree order, matching the release converter's serialization.
    weights = dict(tree_flatten(model.parameters()))

    output.mkdir(parents=True, exist_ok=True)
    weight_path = output / "weights.safetensors"
    if weight_path.exists():
        raise FileExistsError(f"Refusing to overwrite {weight_path}; choose an empty output")

    config = {**dimensions, "model_type": "whisper"}
    mx.save_safetensors(str(weight_path), weights)
    (output / "config.json").write_text(json.dumps(config, indent=2) + "\n")

    # Preserve source decoding metadata for provenance. mlx-whisper callers
    # must still pass language/task explicitly; see README.md.
    for name in ("generation_config.json",):
        source_file = source_dir / name
        if source_file.is_file():
            shutil.copy2(source_file, output / f"source_{name}")

    tensor_bytes = sum(int(value.nbytes) for value in weights.values())
    parameter_count = sum(
        math.prod(value.shape) for key, value in weights.items() if key != "alignment_heads"
    )
    tensor_element_count = sum(math.prod(value.shape) for value in weights.values())
    receipt = {
        "schema_version": 1,
        "created_at": datetime.now(timezone.utc).isoformat(),
        "source_model": source,
        "source_revision": revision,
        "source_files": [path.name for path in files],
        "format": "mlx-whisper-0.4.3",
        "converter_upstream_commit": "cfc5d25acdd387fcf72eb4bb41c608b794633e96",
        "dtype": dtype_name,
        "quantized": False,
        "tensor_count": len(weights),
        "parameter_count": parameter_count,
        "tensor_element_count": tensor_element_count,
        "tensor_bytes": tensor_bytes,
        "weights_file": weight_path.name,
        "weights_bytes": weight_path.stat().st_size,
        "weights_sha256": sha256_file(weight_path),
        "keyset_sha256": hashlib.sha256(("\n".join(sorted(weights)) + "\n").encode()).hexdigest(),
        "strict_load": True,
        "alignment_heads": {
            "shape": list(weights["alignment_heads"].shape),
            "dtype": str(weights["alignment_heads"].dtype),
            "coordinates": alignment_heads,
        },
        "dimensions": dimensions,
        "environment": {
            "python": platform.python_version(),
            "machine": platform.machine(),
            "mlx": importlib.metadata.version("mlx"),
            "mlx_whisper": importlib.metadata.version("mlx-whisper"),
            "safetensors": importlib.metadata.version("safetensors"),
            "torch": importlib.metadata.version("torch"),
        },
    }
    (output / "conversion_receipt.json").write_text(json.dumps(receipt, indent=2) + "\n")
    return receipt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default=SOURCE_MODEL)
    parser.add_argument("--revision", default=SOURCE_REVISION)
    parser.add_argument("--output", type=Path, default=Path("mlx_model"))
    parser.add_argument("--dtype", choices=("float16", "float32"), default="float16")
    return parser.parse_args()


if __name__ == "__main__":
    args = parse_args()
    print(json.dumps(convert(args.source, args.revision, args.output, args.dtype), indent=2))
